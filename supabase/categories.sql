-- SmartQR: categorías como entidad propia. Cada negocio tiene sus categorías, con su propio orden,
-- y cada producto apunta a una (o a ninguna) por products.category_id.
-- Ejecutar en Supabase > SQL Editor DESPUÉS de supabase/products-position.sql y ANTES de desplegar
-- la versión de la app que usa categorías. Se puede correr más de una vez.

begin;

do $$
begin
  if not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'products' and column_name = 'position'
  ) then
    raise exception 'Ejecuta primero supabase/products-position.sql';
  end if;
end $$;

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  name text not null check (char_length(btrim(name)) between 1 and 60),
  -- Orden en la carta (1 = primera)
  position integer,
  created_at timestamptz not null default now()
);

-- Un nombre por negocio, sin distinguir mayúsculas
create unique index if not exists categories_user_name_idx on public.categories (user_id, lower(name));
create index if not exists categories_user_position_idx on public.categories (user_id, position);

alter table public.categories enable row level security;

-- La tienda pública necesita leer las categorías de cualquier negocio
drop policy if exists "Cualquiera puede ver las categorías" on public.categories;
create policy "Cualquiera puede ver las categorías" on public.categories
  for select to anon, authenticated
  using (true);

drop policy if exists "Usuarios crean sus propias categorías" on public.categories;
create policy "Usuarios crean sus propias categorías" on public.categories
  for insert to authenticated
  with check ((select auth.uid()) = user_id);

drop policy if exists "Usuarios editan sus propias categorías" on public.categories;
create policy "Usuarios editan sus propias categorías" on public.categories
  for update to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

drop policy if exists "Usuarios eliminan sus propias categorías" on public.categories;
create policy "Usuarios eliminan sus propias categorías" on public.categories
  for delete to authenticated
  using ((select auth.uid()) = user_id);

-- Si se elimina una categoría, sus productos quedan sin categoría
alter table public.products
  add column if not exists category_id bigint references public.categories (id) on delete set null;

create index if not exists products_category_id_idx on public.products (category_id);

-- Crea una categoría por cada nombre usado en products.category, en el orden en que la carta
-- ya las mostraba (según el primer producto de cada una), y enlaza los productos
insert into public.categories (user_id, name, position)
select user_id, name, row_number() over (partition by user_id order by first_position)
from (
  select user_id, min(btrim(category)) as name, min(coalesce(position, 2147483647)) as first_position
  from public.products
  where btrim(coalesce(category, '')) <> ''
  group by user_id, lower(btrim(category))
) as used
on conflict (user_id, lower(name)) do nothing;

update public.products p
set category_id = c.id
from public.categories c
where p.category_id is null
  and c.user_id = p.user_id
  and lower(c.name) = lower(btrim(p.category));

-- Un producto solo puede usar categorías de su mismo negocio
create or replace function public.check_product_category()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.category_id is not null and not exists (
    select 1 from public.categories c
    where c.id = new.category_id and c.user_id = new.user_id
  ) then
    raise exception 'La categoría no existe o pertenece a otro negocio';
  end if;
  return new;
end;
$$;

drop trigger if exists products_check_category on public.products;
create trigger products_check_category
  before insert or update of category_id, user_id on public.products
  for each row execute function public.check_product_category();

-- Guarda el orden completo de las categorías en una sola llamada (como reorder_products)
create or replace function public.reorder_categories(category_ids bigint[])
returns void
language sql
security invoker
set search_path = ''
as $$
  update public.categories c
  set position = o.ord
  from unnest(category_ids) with ordinality as o (id, ord)
  where c.id = o.id
    and c.user_id = (select auth.uid());
$$;

revoke execute on function public.reorder_categories(bigint[]) from public, anon;
grant execute on function public.reorder_categories(bigint[]) to authenticated;

commit;

-- La columna de texto products.category queda solo por compatibilidad: la app la mantiene con el
-- nombre de la categoría al guardar, pero ya no la usa para agrupar.
